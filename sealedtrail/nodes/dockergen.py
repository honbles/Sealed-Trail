"""Docker packaging: one image, one service per node, role selected by the command (spec 2.4).

Every node is a container of the same image. A `driver` service (compose profile "drive") runs the
workload INSIDE the compose network, so no host ports are needed for 100+ nodes; its result file is
written to ./out. Node state lives on tmpfs (/data), so `docker compose down` leaves nothing behind.

NOT run in the authoring sandbox (no Docker there): treat the first run on your machine as the test.
"""
from __future__ import annotations

import os

DOCKERFILE = """\
# Sealed Trail node image: one image for every role (validator, bank, tsa, na, tiv) and for the driver.
FROM rust:1.75-slim AS crypto
WORKDIR /src/crypto
COPY crypto/ ./
RUN cargo build --release --locked

FROM python:3.12-slim
WORKDIR /app
COPY requirements-node.txt .
RUN pip install --no-cache-dir -r requirements-node.txt
COPY sealedtrail ./sealedtrail
COPY --from=crypto /src/crypto/target/release/libst_crypto.so /usr/local/lib/libst_crypto.so
ENV ST_CRYPTO_LIB=/usr/local/lib/libst_crypto.so ST_HOST=0.0.0.0 ST_DATA=/data ST_TOPOLOGY=/topo/topology.json PYTHONUNBUFFERED=1
ENTRYPOINT ["python", "-m", "sealedtrail.nodes.server", "--port", "8000"]
"""


def compose(topo: dict, out_dir: str, payments: int = 60, workers: int = 8, wait: int = 900, seed: str = "1",
            publish_first_bank: bool = False) -> str:
    os.makedirs(os.path.join(out_dir, "out"), exist_ok=True)
    lines = ["# generated by stctl; one service per node, one image, driver runs inside the network", "services:"]
    first_bank = next((n for n, v in topo["nodes"].items() if v["role"] == "bank"), None)
    for nid, n in topo["nodes"].items():
        lines += [f"  {nid}:", "    image: sealed-trail:latest", "    init: true", "    stop_grace_period: 2s",
                  f"    command: [\"--role\", \"{n['role']}\", \"--id\", \"{nid}\"]",
                  "    volumes:", "      - ./topo:/topo:ro", "    tmpfs:", "      - /data", "    restart: \"no\""]
        if publish_first_bank and nid == first_bank:
            lines += ["    ports:", "      - \"18000:8000\""]
    lines += ["  driver:", "    image: sealed-trail:latest", "    init: true", "    profiles: [\"drive\"]",
              "    entrypoint: [\"python\", \"-m\", \"sealedtrail.nodes.stctl\"]",
              f"    command: [\"drive\", \"--topology\", \"/topo/topology.json\", \"--payments\", \"{payments}\", "
              f"\"--workers\", \"{workers}\", \"--wait\", \"{wait}\", \"--seed\", \"{seed}\", \"--out\", \"/out\"]",
              "    volumes:", "      - ./topo:/topo:ro", "      - ./out:/out"]
    path = os.path.join(out_dir, "docker-compose.yml")
    with open(path, "w") as f:
        f.write("\n".join(lines) + "\n")
    with open(os.path.join(out_dir, "Dockerfile"), "w") as f:
        f.write(DOCKERFILE)
    return path
